<h1>Privacy</h1>
      <p class="date">Effective September 6, 2026</p>
      <p>TouchTips is developed by Harivansh Rathi. The app stores meeting details and notes on your iPhone and does not require an account.</p>
      <h2>Data used by the app</h2>
      <p>With your permission, TouchTips reads your contacts to show people and notice new additions. It uses available location information to suggest meeting places. You can review these suggestions and edit dates, places, and notes.</p>
      <p>The app does not send your contacts, meeting history, or notes to a server operated by the developer. It has no advertising or third-party analytics SDKs.</p>
      <h2>Apple services</h2>
      <p>Maps and place searches use Apple services and may send requests to Apple. These services are covered by <a href="https://www.apple.com/legal/privacy/">Apple’s privacy policy</a>. Contact syncing and device backups follow your iPhone and account settings.</p>
      <h2>Your controls</h2>
      <p>You can change permissions in iPhone Settings. Remove individual meeting records in TouchTips, or use “Delete all data” to clear its records. Your iPhone contacts are kept.</p>
      <h2>Website and support</h2>
      <p>This website uses no cookies or analytics scripts. It is hosted by <a href="https://vercel.com/legal/privacy-policy">Vercel</a>, which processes requests to deliver the pages.</p>
      <p>If you email for help, the developer receives your email address and the information you send, and uses them to respond. For privacy questions, contact <a href="mailto:rathiharivansh@gmail.com?subject=TouchTips%20privacy">rathiharivansh@gmail.com</a>.</p>
